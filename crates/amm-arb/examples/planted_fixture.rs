//! Writes `fixtures/planted.json`: a small synthetic market with one mispriced
//! pool, so `amm-arb scan` has something to find offline.
//!
//! `cargo run -p amm-arb --example planted_fixture -- fixtures/planted.json`

use amm_arb::{fixture::Fixture, synthetic::planted_market};

fn main() {
    let path = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "fixtures/planted.json".to_owned());
    let mut fixture = Fixture::from_market(&planted_market());
    fixture.description = Some(
        "Synthetic WETH/USDC/DAI/WBTC market. The V2 WETH/USDC pair prices WETH 1.2% above every \
         other venue; all other pools agree. Generated by examples/planted_fixture.rs."
            .to_owned(),
    );
    fixture.save(&path).expect("write fixture");
    eprintln!("wrote {path}");
}
